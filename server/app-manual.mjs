/** Retrieve only fixed public manual sections; never interpret a path or URL. */
export function getAppManual(args) {
  if (!args || typeof args !== 'object' || Array.isArray(args) || Object.keys(args).length !== 1 || !Object.hasOwn(args, 'sections')
      || !Array.isArray(args.sections) || args.sections.length < 1 || args.sections.length > 3
      || args.sections.some(id => typeof id !== 'string' || !Object.hasOwn(sections, id))
      || new Set(args.sections).size !== args.sections.length) throw Error('Invalid manual sections');
  return {
    title: 'こつこつ日和の使い方',
    version: '2026-11-21',
    sections: args.sections.map(id => ({id, ...sections[id]})),
  };
}

